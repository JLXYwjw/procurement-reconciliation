def _lit(v):
    """生成字面量表达式的 JSON。"""
    return {"expr": {"Literal": {"Value": v}}}


def _solid(hexv):
    """生成纯色填充的 JSON。"""
    return {"solid": {"color": {"expr": {"Literal": {"Value": "'{}'".format(hexv)}}}}}


def _container(bg, border):
    """生成容器（卡片背景+边框）的 JSON。"""
    return {
        "background": [{"properties": {
            "show": _lit("true"),
            "color": _solid(bg),
            "transparency": _lit("0D")}}],
        "border": [{"properties": {
            "show": _lit("true"),
            "color": _solid(border),
            "radius": _lit("8D"),
            "width": _lit("1D")}}],
    }


