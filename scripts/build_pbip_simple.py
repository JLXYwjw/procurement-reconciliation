MOB_W = 323
MOB_GAP = 8
MOB_SIZE = {
    "textbox": (323, 110),
    "card": (158, 100),
    "tableEx": (323, 270),
    "slicer": (323, 100),
}
MOB_DEFAULT = (323, 180)


def mobile_layout(vs_list):
    """计算手机端每个视觉的位置（卡片两两并排，其余通栏）。"""
    out = {}
    y = 0
    slot = None

    for v in vs_list:
        vt = v["visual"]["visualType"]
        if vt in MOB_SIZE:
            w, h = MOB_SIZE[vt]
        else:
            w, h = MOB_DEFAULT

        if vt == "card":
            if slot is None:
                slot = (y, h)
                out[v["name"]] = (0, y, w, h)
                continue
            sy, sh = slot
            out[v["name"]] = (MOB_W - w, sy, w, h)
            y = sy + max(h, sh) + MOB_GAP
            slot = None
        else:
            if slot is not None:
                y = slot[0] + slot[1] + MOB_GAP
                slot = None
            out[v["name"]] = (0, y, w, h)
            y += h + MOB_GAP

    return out


def mobile_json(v, pos, z):
    """生成单个视觉的手机布局 JSON。"""
    x, y, w, h = pos
    objs = v["visual"].get("objects") or {}

    d = {
        "$schema": MOB_SCHEMA,
        "position": {"x": x, "y": y, "z": z, "width": w, "height": h,
                     "tabOrder": z},
    }

    # 只保留数据点、标签、数值相关的属性
    m_objs = {}
    for k in ("dataPoint", "labels", "calloutValue"):
        if k in objs:
            m_objs[k] = objs[k]
    if m_objs:
        d["objects"] = m_objs

    vco = v["visual"].get("visualContainerObjects")
    if vco:
        d["visualContainerObjects"] = vco

    return d


