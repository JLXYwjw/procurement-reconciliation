def write_platform(item_dir, kind):
    """写 .platform 文件（Fabric 工程的元数据）。"""
    data = {
        "$schema": f"{FABRIC}/gitIntegration/platformProperties/2.0.0/schema.json",
        "metadata": {"type": kind, "displayName": PROJ},
        "config": {"version": "2.0", "logicalId": LOGICAL_ID},
    }
    with open(os.path.join(item_dir, ".platform"), "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)


