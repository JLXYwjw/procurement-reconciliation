def dtype_map(df, col):
    """根据 pandas dtype 推断 TMDL 数据类型。"""
    t = df[col].dtype
    if pd.api.types.is_integer_dtype(t):
        return "int64"
    if pd.api.types.is_float_dtype(t):
        return "double"
    if pd.api.types.is_datetime64_any_dtype(t):
        return "dateTime"
    if col.lower().endswith("date") or col in ("creation_date", "purchase_date"):
        return "dateTime"
    # 其余都是字符串
    return "string"


def m_type(tmdl_type):
    """TMDL 类型 → M 表达式里的类型名。"""
    mapping = {
        "int64": "Int64.Type",
        "double": "type number",
        "dateTime": "type date",
        "string": "type text",
    }
    return mapping[tmdl_type]


# 金额列需要 $#,0 格式
MONEY_COLS = {
    "total_price", "unit_price", "total_spend",
    "top_segment_spend", "top_department_spend", "avg_order",
}

# 百分比列需要 0.0% 格式
PCT_COLS = {
    "top_segment_share", "top_department_share", "dept_cum_share",
}


def table_tmdl(rel):
    """生成一张表的 TMDL 列定义文本。"""
    df = pd.read_csv(os.path.join(CSV_DIR, rel), encoding="utf-8")
    cols = []
    types = {}
    lines = []

    for c in df.columns:
        t = dtype_map(df, c)
        cols.append(c)
        types[c] = t
        lines.append(f"\tcolumn '{c}'")
        lines.append(f"\t\tdataType: {t}")
        lines.append(f"\t\tsummarizeBy: none")
        lines.append(f"\t\tsourceColumn: {c}")
        if c in MONEY_COLS:
            lines.append(f"\t\tformatString: $#,0")
        elif c in PCT_COLS:
            lines.append(f"\t\tformatString: 0.0%")

    return "\n".join(lines), cols, types


def m_expr(rel, cols, types):
    """生成分区的 M 表达式（Power Query 加载 CSV）。"""
    # 构造类型转换列表
    tr_parts = []
    for c in cols:
        tr_parts.append(f'{{"{c}", {m_type(types[c])}}}')
    tr = ", ".join(tr_parts)

    # 用绝对路径，不走 pCsvFolder 参数（避免部分 Desktop 版本参数不赋值）
    abs_path = CSV_DIR.replace(os.sep, "/").rstrip("/") + "/" + rel

    expr = (
        f'\t\tsource =\n'
        f'\t\t\tlet\n'
        f'\t\t\t\tSource = Csv.Document(File.Contents("{abs_path}"), '
        f'[Delimiter=",", Columns={len(cols)}, Encoding=65001, QuoteStyle=QuoteStyle.Csv]),\n'
        f'\t\t\t\tHeadered = Table.PromoteHeaders(Source, [PromoteAllScalars=true]),\n'
        f'\t\t\t\tTyped = Table.TransformColumnTypes(Headered, {{{tr}}})\n'
        f'\t\t\tin\n'
        f'\t\t\t\tTyped'
    )
    return expr


