def textbox(name, x, y, w, h, main, sub=""):
    """生成页眉文本框。"""
    def _para(text, size, bold, color):
        style = {
            "fontFamily": "'Segoe UI Semibold','wf_standard-font','Arial',sans-serif",
            "fontSize": size,
            "color": {"solid": {"color": _lit(color)}},
        }
        if bold:
            style["bold"] = True
        return {"textRuns": [{"value": text, "textStyle": style}],
                "alignment": "left"}

    paras = [_para(main, "18pt", True, INK)]
    if sub:
        paras.append(_para(sub, "10pt", False, INK_2))

    return {
        "$schema": "https://developer.microsoft.com/json-schemas/fabric/item/report/definition/visualContainer/2.0.0/schema.json",
        "name": name,
        "position": {"x": x, "y": y, "z": 0, "width": w, "height": h, "tabOrder": 0},
        "visual": {
            "visualType": "textbox",
            "query": {"queryState": {}, "sortDefinition": {"sort": []}},
            "objects": {"general": [{"properties": {"paragraphs": paras}}]},
            "drillFilterOtherVisuals": True,
        },
    }


