def build_semantic_model():
    """生成整个语义模型目录结构和 TMDL 文件。"""
    # 清掉旧目录
    shutil.rmtree(SM_DIR, ignore_errors=True)

    # 建目录
    tables_dir = os.path.join(SM_DIR, "definition", "tables")
    cultures_dir = os.path.join(SM_DIR, "definition", "cultures")
    os.makedirs(tables_dir, exist_ok=True)
    os.makedirs(cultures_dir, exist_ok=True)

    # definition.pbism
    pbism = {
        "$schema": f"{FABRIC}/item/semanticModel/definitionProperties/1.0.0/schema.json",
        "version": "4.0", "settings": {},
    }
    with open(os.path.join(SM_DIR, "definition.pbism"), "w", encoding="utf-8") as f:
        json.dump(pbism, f, ensure_ascii=False, indent=2)

    write_platform(SM_DIR, "SemanticModel")

    # expressions.tmdl（CSV 路径参数）
    csv_path = CSV_DIR.replace(os.sep, "/").rstrip("/") + "/"
    expr_content = (
        "/// 共享表达式：CSV 数据源根目录\n"
        "/// 换机器时只需在这里改一处\n"
        f'expression \'pCsvFolder\' = "{csv_path}" '
        'meta [IsParameterQuery=true, Type="Text", IsParameterQueryRequired=true]\n'
    )
    with open(os.path.join(SM_DIR, "definition", "expressions.tmdl"),
              "w", encoding="utf-8") as f:
        f.write(expr_content)

    # 两张表的配置
    tables = ["fact_procurement", "dim_supplier"]
    descs = {
        "fact_procurement": "采购订单事实表：CA 州 2012-2015 采购明细，346k 行",
        "dim_supplier": "供应商维表：KMeans 聚类后的供应商分层",
    }
    measures_map = {
        "fact_procurement": MEASURES_FACT,
        "dim_supplier": MEASURES_DIM_SUPPLIER,
    }

    # model.tmdl 头部
    model_lines = [
        f"model {PROJ}",
        "\tculture: zh-CN",
        "\tdefaultPowerBIDataSourceVersion: powerBI_V3",
        "\tsourceQueryCulture: zh-CN",
        "",
    ]

    # 逐表生成 TMDL
    for t in tables:
        rel = t + ".csv"
        if not os.path.exists(os.path.join(CSV_DIR, rel)):
            print(f"! 跳过缺失表 {rel}")
            continue

        body, cols, types = table_tmdl(rel)
        content = f"/// {descs[t]}\n" + f"table {t}\n\n" + body
        if t in measures_map:
            content += "\n" + measures_map[t]
        content += f"\n\n\tpartition {t} = m\n\t\tmode: import\n" + m_expr(rel, cols, types) + "\n"

        with open(os.path.join(tables_dir, f"{t}.tmdl"),
                  "w", encoding="utf-8", newline="\n") as f:
            f.write(content)
        print(f"  + tables/{t}.tmdl  ({len(cols)} 列)")

    # relationships.tmdl
    rel_lines = [
        "relationship rel_supplier_fact",
        "\tfromColumn: fact_procurement.supplier_name",
        "\ttoColumn: dim_supplier.supplier_name",
        "",
    ]
    with open(os.path.join(SM_DIR, "definition", "relationships.tmdl"),
              "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(rel_lines))
    print(f"  + relationships.tmdl  (1 条关系)")

    # model.tmdl
    with open(os.path.join(SM_DIR, "definition", "model.tmdl"),
              "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(model_lines) + "\n")

    # database.tmdl
    with open(os.path.join(SM_DIR, "definition", "database.tmdl"),
              "w", encoding="utf-8", newline="\n") as f:
        f.write("database\n\tcompatibilityLevel: 1700\n")

    # cultures/zh-CN.tmdl
    with open(os.path.join(cultures_dir, "zh-CN.tmdl"),
              "w", encoding="utf-8", newline="\n") as f:
        f.write("culture zh-CN\n")


