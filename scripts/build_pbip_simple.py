# 1. 去 BOM：Power Query 会把 \ufeff 当成列名的一部分
# ------------------------------------------------------------------
def strip_bom():
    """遍历 CSV 目录，去掉每个 CSV 文件开头的 BOM 标记。"""
    for f in os.listdir(CSV_DIR):
        if not f.endswith(".csv"):
            continue
        p = os.path.join(CSV_DIR, f)
        raw = open(p, "rb").read()
        if raw.startswith(b"\xef\xbb\xbf"):
            open(p, "wb").write(raw[3:])
            print(f"  BOM 已去除: {f}")


