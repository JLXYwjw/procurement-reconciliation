def col_ref(entity, prop):
    """生成列引用的 JSON 结构。"""
    return {"field": {"Column": {"Expression": {"SourceRef": {"Entity": entity}},
                                "Property": prop}}}


def meas_ref(entity, prop):
    """生成度量值引用的 JSON 结构。"""
    return {"field": {"Measure": {"Expression": {"SourceRef": {"Entity": entity}},
                                 "Property": prop}}}


def agg_ref(entity, prop, fn):
    """生成聚合引用的 JSON 结构。fn 是聚合函数编号（0=Sum, 2=DistinctCount...）。"""
    return {"field": {"Aggregation": {
        "Expression": {"Column": {"Expression": {"SourceRef": {"Entity": entity}},
                                  "Property": prop}},
        "Function": fn}}}


