def _ref_base(item, fallback):
    """从投影对象里提取字段引用的可读名称。"""
    fld = item.get("field", {})
    try:
        if "Measure" in fld:
            m = fld["Measure"]
            return "{}.{}".format(m["Expression"]["SourceRef"]["Entity"], m["Property"])
        if "Aggregation" in fld:
            a = fld["Aggregation"]
            c = a["Expression"]["Column"]
            fn_map = {0: "Sum", 1: "Average", 2: "DistinctCount",
                      3: "Min", 4: "Max", 5: "Count",
                      6: "Median", 7: "StdDev", 8: "Variance"}
            fn = fn_map.get(a.get("Function"), str(a.get("Function")))
            return "{}({}.{})".format(fn,
                                     c["Expression"]["SourceRef"]["Entity"],
                                     c["Property"])
        if "Column" in fld:
            c = fld["Column"]
            return "{}.{}".format(c["Expression"]["SourceRef"]["Entity"], c["Property"])
    except (KeyError, TypeError):
        pass
    return fallback


def visual(name, vtype, projections, x, y, w, h,
           title="", accent="", panel=False, tint="", sort=None, labels=False):
    """生成一个视觉对象的 JSON。"""
    state = {}
    used = set()

    # 为每个投影分配 queryRef
    for role, items in projections.items():
        new_items = []
        for i, it in enumerate(items):
            it = dict(it)
            base = "{}.{}".format(role, _ref_base(it, "f{}".format(i)))
            qref = base
            n = 2
            while qref in used:
                qref = "{}_{}".format(base, n)
                n += 1
            used.add(qref)
            it["queryRef"] = qref
            new_items.append(it)
        state[role] = {"projections": new_items}

    # 视觉属性
    objs = {}
    if title:
        objs["title"] = [{"properties": {
            "text": {"expr": {"Literal": {"Value": "'{}'".format(title)}}},
            "show": _lit("true"),
            "fontColor": _solid(INK),
            "fontSize": _lit("11D"),
            "bold": _lit("true")}}]

    main_color, light_bg = ACCENT.get(accent, ("", ""))
    if main_color:
        objs["dataPoint"] = [{"properties": {"fill": _solid(main_color)}}]
        if vtype == "card":
            for obj_name in ("labels", "calloutValue"):
                objs[obj_name] = [{"properties": {
                    "color": _solid(main_color),
                    "fontColor": _solid(main_color)}}]

    if labels and vtype != "card":
        objs["labels"] = [{"properties": {"show": _lit("true")}}]

    # 排序定义
    sort_def = {"sort": []}
    if sort:
        field, direction = sort
        if isinstance(field, dict) and set(field.keys()) == {"field"}:
            field = field["field"]
        sort_def = {"sort": [{"field": field, "direction": direction}]}

    out = {
        "$schema": "https://developer.microsoft.com/json-schemas/fabric/item/report/definition/visualContainer/2.0.0/schema.json",
        "name": name,
        "position": {"x": x, "y": y, "z": 0, "width": w, "height": h, "tabOrder": 0},
        "visual": {
            "visualType": vtype,
            "query": {"queryState": state, "sortDefinition": sort_def},
            "objects": objs,
            "drillFilterOtherVisuals": True,
        },
    }

    if panel:
        out["visual"]["visualContainerObjects"] = _container(
            tint or light_bg or PANEL_BG, main_color or PANEL_BD)

    return out


